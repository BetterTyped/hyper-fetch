/**
 * @vitest-environment node
 *
 * Differential tests against a real AI SDK (v7) backend: `streamText` with a scripted mock model and real tools. The
 * AI SDK's own client and our `Chat` hold the same conversation with it - same messages in, same model prompts on the
 * server, same assistant message out. The backend validates every request body with `validateUIMessages`, so a body
 * the AI SDK would reject fails the test.
 */
import type { ChatToolPartType } from "@hyper-fetch/ai";
import { aiSDKProtocol } from "@hyper-fetch/ai";
import type { ModelMessage, UIMessage } from "ai";

import { comparableParts, oursAsParts, ReferenceChat } from "./ai-sdk.reference";
import type { ServerScriptType } from "./ai-sdk.server";
import { createAISDKServer, toServerModelMessages } from "./ai-sdk.server";
import { createHarnessChat } from "./chat.harness";

/** The part of the backend's types these tests touch from the client */
type Types = {
  metadata: { model: string; steps?: number };
  tools: {
    askConfirmation: { input: { question: string }; output: { confirmed: boolean } };
    deleteFile: { input: { path: string }; output: { deleted: string } };
  };
};

const createClients = (script: ServerScriptType) => {
  const referenceServer = createAISDKServer(script);
  const reference = new ReferenceChat({ responses: (request) => referenceServer.respond(request.messages) });

  const ourServer = createAISDKServer(script);
  const { chat: ours, calls } = createHarnessChat<Types>({
    protocol: aiSDKProtocol(),
    respond: (payload) => ourServer.respond(payload.messages),
  });

  return { reference, referenceServer, ours, ourServer, calls };
};

/** Ids generated by the backend differ between the two conversations - replace them by their order of appearance. */
const stableIds = <T>(value: T): T => {
  const seen = new Map<string, string>();
  return JSON.parse(
    JSON.stringify(value, (key, item: unknown) => {
      if ((key === "id" || key === "approvalId") && typeof item === "string" && item.startsWith("aitxt-")) {
        if (!seen.has(item)) {
          seen.set(item, `generated-${seen.size}`);
        }
        return seen.get(item);
      }
      return item;
    }),
  ) as T;
};

const toModelMessages = (requests: UIMessage[][]): Promise<ModelMessage[][]> =>
  Promise.all(requests.map((messages) => toServerModelMessages(messages)));

const expectSameConversation = async ({
  reference,
  referenceServer,
  ours,
  ourServer,
}: ReturnType<typeof createClients>) => {
  expect(reference.error).toBeUndefined();
  expect(ours.error).toBeUndefined();
  expect(ours.status).toBe("ready");

  // Same assistant messages on both clients
  const referenceAssistants = reference.messages.filter((message) => message.role === "assistant");
  const ourAssistants = ours.messages.filter((message) => message.role === "assistant");
  expect(ourAssistants).toHaveLength(referenceAssistants.length);
  ourAssistants.forEach((message, index) => {
    expect(stableIds(oursAsParts(message))).toEqual(stableIds(comparableParts(referenceAssistants[index])));
    expect(message.metadata).toEqual(referenceAssistants[index].metadata);
  });

  // Same number of requests and model calls, and the model saw the same prompts
  expect(ourServer.requests).toHaveLength(referenceServer.requests.length);
  expect(ourServer.modelCalls()).toBe(referenceServer.modelCalls());
  expect(stableIds(await toModelMessages(ourServer.requests))).toEqual(
    stableIds(await toModelMessages(referenceServer.requests)),
  );
};

const findTool = (clients: ReturnType<typeof createClients>, toolCallId: string) => {
  const ours = clients.ours.messages
    .flatMap((message) => message.parts)
    .find((part): part is ChatToolPartType<Types> => part.type === "tool" && part.toolCallId === toolCallId);
  const reference = clients.reference.messages
    .flatMap((message) => message.parts as { toolCallId?: string; approval?: { id: string } }[])
    .find((part) => part.toolCallId === toolCallId);
  if (!ours || !reference) {
    throw new Error(`Tool call ${toolCallId} not found`);
  }
  return { ours, reference };
};

const sendBoth = async (clients: ReturnType<typeof createClients>, text?: string) => {
  await clients.reference.sendMessage(text === undefined ? undefined : { text });
  await clients.ours.sendMessage(text);
};

describe("AI SDK differential [ real backend ]", () => {
  describe("when the backend answers in one request", () => {
    const scripts: Record<string, ServerScriptType> = {
      "plain text": [{ text: "Hello from the model." }],
      "reasoning, text, sources and files": [
        {
          reasoning: "The user wants a picture and links.",
          text: "Here you go.",
          sources: [
            { id: "s1", url: "https://example.com/a", title: "A" },
            { id: "s2", url: "https://example.com/b" },
          ],
          files: [{ mediaType: "image/png", base64: "iVBORw0KGgo=" }],
        },
      ],
      "a server tool between two texts": [
        { text: "Let me check. ", toolCalls: [{ id: "call-1", name: "getWeather", input: { city: "Oslo" } }] },
        { text: "It is 21 degrees in Oslo." },
      ],
      "reasoning in every step": [
        {
          reasoning: "I need the weather.",
          toolCalls: [{ id: "call-1", name: "getWeather", input: { city: "Oslo" } }],
        },
        { reasoning: "Now I know.", text: "21 degrees." },
      ],
      "three steps of tool calls": [
        { toolCalls: [{ id: "call-1", name: "getWeather", input: { city: "Oslo" } }] },
        { text: "One more. ", toolCalls: [{ id: "call-2", name: "getWeather", input: { city: "Rome" } }] },
        { text: "Both are 21 degrees." },
      ],
      "text after a tool call in the same step": [
        {
          text: "Before. ",
          toolCalls: [{ id: "call-1", name: "getWeather", input: { city: "Oslo" } }],
          after: "After.",
        },
        { text: "Done." },
      ],
      "a failing tool": [
        { toolCalls: [{ id: "call-1", name: "failing", input: { reason: "disk full" } }] },
        { text: "The tool failed." },
      ],
      "a tool with preliminary results": [
        { toolCalls: [{ id: "call-1", name: "research", input: { topic: "sse" } }] },
        { text: "Research finished." },
      ],
      "a tool that fails after a preliminary result": [
        { toolCalls: [{ id: "call-1", name: "researchThenFail", input: { topic: "sse" } }] },
        { text: "Research failed." },
      ],
      "a dynamic tool": [
        { toolCalls: [{ id: "call-1", name: "lookup", input: { key: "answer" } }] },
        { text: "Found it." },
      ],
      "a tool call with input that fails validation": [
        { toolCalls: [{ id: "call-1", name: "getWeather", input: { city: 42 } }] },
        { text: "I sent bad input." },
      ],
      "a tool call with input that is not JSON": [
        { toolCalls: [{ id: "call-1", name: "getWeather", input: null, raw: '{"city": "Os' }] },
        { text: "I sent broken JSON." },
      ],
      "a call to a tool that does not exist": [
        { toolCalls: [{ id: "call-1", name: "doesNotExist", input: { a: 1 } }] },
        { text: "No such tool." },
      ],
      "every kind of tool call in parallel": [
        {
          text: "Running everything. ",
          toolCalls: [
            { id: "call-1", name: "getWeather", input: { city: "Oslo" } },
            { id: "call-2", name: "failing", input: { reason: "x" } },
            { id: "call-3", name: "research", input: { topic: "a" } },
            { id: "call-4", name: "researchThenFail", input: { topic: "b" } },
            { id: "call-5", name: "lookup", input: { key: "k" } },
            { id: "call-6", name: "getWeather", input: {} },
            { id: "call-7", name: "missing", input: {} },
          ],
        },
        { text: "All done." },
      ],
    };

    it.each(Object.keys(scripts))("should match the AI SDK client for %s", async (name) => {
      const clients = createClients(scripts[name]);

      await sendBoth(clients, "Go");

      await expectSameConversation(clients);
    });

    it.each(Object.keys(scripts))("should send a history the backend accepts after %s", async (name) => {
      const clients = createClients([...scripts[name], { text: "Follow-up answer." }]);

      await sendBoth(clients, "Go");
      await sendBoth(clients, "And then?");

      await expectSameConversation(clients);
      expect(clients.ours.messages).toHaveLength(4);
    });
  });

  describe("when the client has to answer", () => {
    it("should continue after a client tool result", async () => {
      const clients = createClients([
        {
          text: "I need your OK. ",
          toolCalls: [{ id: "call-1", name: "askConfirmation", input: { question: "Sure?" } }],
        },
        { text: "Thanks for confirming." },
      ]);
      await sendBoth(clients, "Do it");
      expect(findTool(clients, "call-1").ours.state).toBe("input-available");

      await clients.reference.addToolOutput({
        tool: "askConfirmation",
        toolCallId: "call-1",
        output: { confirmed: true },
      });
      clients.ours.addToolResult({ tool: "askConfirmation", toolCallId: "call-1", output: { confirmed: true } });
      await sendBoth(clients);

      await expectSameConversation(clients);
      expect(clients.ours.messages).toHaveLength(2);
      expect(clients.ourServer.requests).toHaveLength(2);
    });

    it("should continue after a client tool error", async () => {
      const clients = createClients([
        { toolCalls: [{ id: "call-1", name: "askConfirmation", input: { question: "Sure?" } }] },
        { text: "The dialog could not be shown." },
      ]);
      await sendBoth(clients, "Do it");

      await clients.reference.addToolOutput({
        tool: "askConfirmation",
        toolCallId: "call-1",
        state: "output-error",
        errorText: "Dialog blocked",
      });
      clients.ours.addToolResult({
        tool: "askConfirmation",
        toolCallId: "call-1",
        state: "output-error",
        errorText: "Dialog blocked",
      });
      await sendBoth(clients);

      await expectSameConversation(clients);
    });

    it.each([
      { name: "approved", approved: true, reason: undefined },
      { name: "approved with a reason", approved: true, reason: "Go ahead" },
      { name: "denied", approved: false, reason: undefined },
      { name: "denied with a reason", approved: false, reason: "Too dangerous" },
    ])("should continue after a tool approval is $name", async ({ approved, reason }) => {
      const clients = createClients([
        { text: "Deleting. ", toolCalls: [{ id: "call-1", name: "deleteFile", input: { path: "/tmp/x" } }] },
        { text: approved ? "Deleted." : "Not deleted." },
      ]);
      await sendBoth(clients, "Delete /tmp/x");
      const pending = findTool(clients, "call-1");
      if (pending.ours.state !== "approval-requested" || !pending.reference.approval) {
        throw new Error("Expected an approval request on both clients");
      }

      await clients.reference.addToolApprovalResponse({ id: pending.reference.approval.id, approved, reason });
      clients.ours.addToolApprovalResponse({ id: pending.ours.approval.id, approved, reason });
      await sendBoth(clients);

      await expectSameConversation(clients);
      expect(findTool(clients, "call-1").ours.state).toBe(approved ? "output-available" : "output-denied");
    });

    it("should keep a conversation going over several turns with tools and approvals", async () => {
      const clients = createClients([
        { text: "Checking. ", toolCalls: [{ id: "call-1", name: "getWeather", input: { city: "Oslo" } }] },
        { text: "21 degrees." },
        { toolCalls: [{ id: "call-2", name: "deleteFile", input: { path: "/a" } }] },
        { text: "Deleted /a. ", toolCalls: [{ id: "call-3", name: "askConfirmation", input: { question: "More?" } }] },
        { text: "All done." },
        { text: "You are welcome." },
      ]);

      await sendBoth(clients, "Weather?");
      await sendBoth(clients, "Now delete /a");
      const pending = findTool(clients, "call-2");
      if (pending.ours.state !== "approval-requested" || !pending.reference.approval) {
        throw new Error("Expected an approval request on both clients");
      }
      await clients.reference.addToolApprovalResponse({ id: pending.reference.approval.id, approved: true });
      clients.ours.addToolApprovalResponse({ id: pending.ours.approval.id, approved: true });
      await sendBoth(clients);
      await clients.reference.addToolOutput({
        tool: "askConfirmation",
        toolCallId: "call-3",
        output: { confirmed: false },
      });
      clients.ours.addToolResult({ tool: "askConfirmation", toolCallId: "call-3", output: { confirmed: false } });
      await sendBoth(clients);
      await sendBoth(clients, "Thanks");

      await expectSameConversation(clients);
      expect(clients.ours.messages.map((message) => message.role)).toEqual([
        "user",
        "assistant",
        "user",
        "assistant",
        "user",
        "assistant",
      ]);
      expect(clients.ourServer.modelCalls()).toBe(6);
    });
  });
});
