import { Slot } from "@radix-ui/react-slot";
import type { VariantProps } from "class-variance-authority";
import { cva } from "class-variance-authority";
import * as React from "react";

import { cn } from "@/lib/utils";

/**
 * Sidebar building blocks, based on the shadcn/ui sidebar. HyperFlow's sidebars are always shown, so the collapsing,
 * mobile sheet, keyboard shortcut and persisted state of the original are left out.
 */

const SIDEBAR_WIDTH = "16rem";

function SidebarProvider({ className, style, children, ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="sidebar-wrapper"
      style={{ "--sidebar-width": SIDEBAR_WIDTH, ...style } as React.CSSProperties}
      className={cn("group/sidebar-wrapper flex min-h-svh w-full", className)}
      {...props}
    >
      {children}
    </div>
  );
}

function Sidebar({
  className,
  children,
  // Kept for the call sites: HyperFlow's sidebars are inset and never collapse
  variant: _variant,
  collapsible: _collapsible,
  ...props
}: React.ComponentProps<"div"> & {
  variant?: "sidebar" | "floating" | "inset";
  collapsible?: "none";
}) {
  return (
    <div
      data-slot="sidebar"
      data-sidebar="sidebar"
      className={cn("bg-sidebar text-sidebar-foreground flex h-full w-(--sidebar-width) flex-col", className)}
      {...props}
    >
      {children}
    </div>
  );
}

